/* แถวที่ไม่มีเลขที่คำสั่งซื้อ (แถวสรุปท้ายไฟล์) ต้องถูกข้าม ไม่ใช่กลายเป็นออเดอร์เปล่า */
var TAIL = [
  ['หมายเลขคำสั่งซื้อ', 'สถานะการสั่งซื้อ', 'ชื่อสินค้า', 'จำนวน', 'ราคาขาย'],
  ['X1', 'ที่ต้องจัดส่ง', 'ของทดสอบ', 1, 10],
  ['', '', 'รวมทั้งสิ้น', '', 10]
];
var tl = S.shopeeParse(TAIL, S.shopeeMatchCols(TAIL[0]), 0);
