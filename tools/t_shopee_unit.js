eq('วันที่อ่านไม่ออก คืนค่าว่าง ไม่เดาเป็นวันนี้', S.shopeeDate_('เมื่อวาน'), '');
eq('ตัวเลขที่มีลูกน้ำและสัญลักษณ์เงิน', S.shopeeNum_('฿1,234.50'), 1234.5);
eq('ยกเลิก', S.shopeeStatusKind('ยกเลิกแล้ว'), 'cancelled');
eq('คืนสินค้า/คืนเงิน', S.shopeeStatusKind('การคืนสินค้า/คืนเงิน'), 'returned');
eq('สำเร็จ', S.shopeeStatusKind('สำเร็จแล้ว'), 'done');

/* ไม่มีคอลัมน์ราคาต่อชิ้น มีแต่ยอดรวมบรรทัด — ต้องหารกลับให้ถูก
   ถ้าปล่อยราคาเป็น 0 ยอดขายในชีทจะกลายเป็นศูนย์ทั้งใบโดยไม่มีอะไรเตือน */
var NOPRICE = [
  ['หมายเลขคำสั่งซื้อ', 'สถานะการสั่งซื้อ', 'ชื่อสินค้า', 'จำนวน', 'ยอดขายสินค้า(฿)'],
  ['X1', 'ที่ต้องจัดส่ง', 'ของทดสอบ', 4, 500]
];
var np = S.shopeeParse(NOPRICE, S.shopeeMatchCols(NOPRICE[0]), 0);
