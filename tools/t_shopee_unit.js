var hr = S.shopeeHeaderRow(TH_ROWS);
eq('หาแถวหัวตารางเจอ แม้มีบรรทัดคำอธิบายอยู่ข้างบน', hr, 1);

var cols = S.shopeeMatchCols(TH_ROWS[hr]);
eq('จับคอลัมน์เลขที่คำสั่งซื้อ', cols.sn, 0);
eq('จับคอลัมน์รหัส SKU ฝั่ง Shopee', cols.code, 5);
eq('จับคอลัมน์จำนวน', cols.qty, 6);
eq('จับคอลัมน์ราคาขาย ไม่ใช่ยอดขาย', cols.price, 7);
eq('จับคอลัมน์ค่าคอมมิชชั่น', cols.fee, 9);
eq('จับคอลัมน์ค่าบริการแยกจากค่าคอมมิชชั่น', cols.fee2, 10);

var r = S.shopeeParse(TH_ROWS, cols, hr);
eq('สองแถวของใบเดียวกันรวมเป็นใบเดียว', r.orders.length, 2);
eq('ใบแรกมีสองรายการ', r.orders[0].items.length, 2);
eq('วันที่อ่านออกเป็น ISO', r.orders[0].date, '2026-09-01');
eq('ชื่อผู้รับเก็บจากแถวแรก ไม่หายตอนแถวสองว่าง', r.orders[0].recip, 'คุณเอ ทดสอบ');
eq('ค่าธรรมเนียม = คอมมิชชั่น + ค่าบริการ ของแถวแรกเท่านั้น', r.orders[0].fee, 30.8);
eq('เลขพัสดุติดมาด้วย', r.orders[0].track, 'TH0011');
eq('สถานะที่ต้องจัดส่ง = กลุ่มที่ตัดสต๊อกได้', r.orders[0].kind, 'toship');
eq('ยังไม่ชำระเงิน = ไม่อยู่ในกลุ่มที่ตัดสต๊อก',
  S.SHOPEE_CUT_KINDS.indexOf(r.orders[1].kind), -1);

