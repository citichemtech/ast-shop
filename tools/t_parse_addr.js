/*
 * อ่านที่อยู่ที่ลูกค้าพิมพ์มาในแชท
 *
 *   node tools/t_parse_addr.js
 *
 * ช่อง "วางที่อยู่จากแชท" โฆษณาไว้ว่ารับที่อยู่จาก Shopee / Lazada / Line ได้
 * แต่ของเดิมอ่านได้เฉพาะข้อความสรุปที่แอปสร้างเอง พอวางที่อยู่ดิบที่ลูกค้าพิมพ์มา
 * จึงขึ้นว่า "อ่านข้อความไม่ออก" ทั้งที่ข้อความนั้นไม่มีอะไรผิด
 * ผลคือคนใช้ต้องพิมพ์ที่อยู่เองอยู่ดี ซึ่งลบเหตุผลทั้งหมดของการมีช่องนี้
 *
 * ที่อยู่ที่พิมพ์ผิดหนึ่งตัวคือของที่ส่งไปผิดบ้าน จึงคุมด้วยข้อความจริงหลายแบบ
 * ที่ลูกค้าส่งมา ไม่ใช่แบบที่เราคิดเองว่าเขาน่าจะพิมพ์
 */
'use strict';
var fs = require('fs');
var vm = require('vm');
var path = require('path');

var fails = 0;
function eq(label, got, want) {
  var ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) fails++;
  console.log((ok ? '  ok   ' : '  FAIL ') + label +
    '  ได้ ' + JSON.stringify(got) + (ok ? '' : '  ควรได้ ' + JSON.stringify(want)));
}
function truthy(label, got) {
  if (!got) fails++;
  console.log((got ? '  ok   ' : '  FAIL ') + label + '  ได้ ' + JSON.stringify(got));
}

var src = fs.readFileSync(path.join(__dirname, '..', 'apps-script', 'Parse.html'), 'utf8')
  .replace(/<\/?script>/g, '');
var ctx = { CFG: { products: [] }, console: console };
vm.createContext(ctx);
vm.runInContext(src, ctx, { filename: 'Parse.html' });
var P = ctx.parseOrderText;

/* ============================================================ 1. ของจริง */
console.log('\n1. ที่อยู่ที่ลูกค้าส่งมาจริง (14 ก.ย. 69)');
var a = P('Watvannneany\nร้านแต่งรถตู้\n22/8 ถ.สุขวิท ต.เนินพระ\n อ.เมือง จ.ระยอง 21000\n083-4988949');
eq('ชื่อผู้รับ', a.cust, 'Watvannneany');
eq('เบอร์โทร (ตัดขีดออก เก็บศูนย์หน้าไว้)', a.tel, '0834988949');
eq('ตำบล', a.tambon, 'เนินพระ');
eq('อำเภอ', a.amphoe, 'เมือง');
eq('จังหวัด', a.province, 'ระยอง');
eq('รหัสไปรษณีย์', a.zip, '21000');
/* ชื่อร้านต้องไม่หายไปไหน — บนใบปะหน้าต้องมี ไม่งั้นคนส่งของหาไม่เจอ */
truthy('ชื่อร้านยังอยู่ในที่อยู่', a.addr.indexOf('ร้านแต่งรถตู้') > -1);
truthy('บ้านเลขที่กับถนนยังอยู่', a.addr.indexOf('22/8') > -1);

/* ============================================================ 2. แบบอื่น ๆ */
