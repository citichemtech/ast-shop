eq('ตัดป้ายชื่อออก', e.cust, 'ร้านเสนา แวนมาสเตอร์');
eq('ตัดป้ายเบอร์ออก', e.tel, '0820001111');
eq('จังหวัด', e.province, 'สงขลา');

/* ================================================= 3. สิ่งที่ต้องไม่เดามั่ว */
console.log('\n3. สิ่งที่ต้องไม่เดามั่ว');
/* เลขที่บ้านกับรหัสไปรษณีย์เป็นตัวเลขเหมือนกัน แต่ไม่ใช่เบอร์โทร
   เดาผิดคือใบปะหน้าพิมพ์เบอร์ที่โทรไม่ติด แล้วของตีกลับ */
var f = P('บริษัท ทดสอบ จำกัด\n88/8 ถ.ทดสอบ ต.ทดสอบ อ.ทดสอบ จ.ชลบุรี 20000');
