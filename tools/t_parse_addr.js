eq('แยกชื่อออกจากเบอร์ได้', b.cust, 'คุณสมชาย ใจดี');
eq('ได้เบอร์', b.tel, '0812345678');
eq('ได้จังหวัด', b.province, 'สมุทรปราการ');

console.log('\n   ใช้คำเต็ม ตำบล/อำเภอ/จังหวัด');
var c = P('นางสาวมาลี ดอกไม้\n12 หมู่ 3 ตำบลในเมือง อำเภอเมือง จังหวัดขอนแก่น 40000\nโทร 0899999999');
eq('ชื่อ', c.cust, 'นางสาวมาลี ดอกไม้');
eq('ตำบล', c.tambon, 'ในเมือง');
eq('อำเภอ', c.amphoe, 'เมือง');
eq('จังหวัด', c.province, 'ขอนแก่น');
eq('เบอร์จากบรรทัดที่ขึ้นต้นว่า โทร', c.tel, '0899999999');

console.log('\n   กรุงเทพฯ ใช้ แขวง/เขต ไม่ใช่ ตำบล/อำเภอ');
var d = P('สมหญิง รักดี\n51/45 ซ.ลาดกระบัง 12 แขวงลาดกระบัง เขตลาดกระบัง กรุงเทพมหานคร 10520\n0611111111');
